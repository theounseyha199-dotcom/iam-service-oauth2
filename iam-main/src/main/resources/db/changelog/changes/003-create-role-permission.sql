CREATE TABLE role_permissions (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                  role_id BIGINT NOT NULL,
                                  permission_id BIGINT NOT NULL,

                                  assigned_at TIMESTAMPTZ NOT NULL,
                                  assigned_by VARCHAR(100) NOT NULL,

                                  expires_at TIMESTAMPTZ,

                                  revoked_at TIMESTAMPTZ,
                                  revoked_by VARCHAR(100),

                                  reason VARCHAR(255),

                                  CONSTRAINT fk_role_permissions_role
                                      FOREIGN KEY (role_id)
                                          REFERENCES roles (id),

                                  CONSTRAINT fk_role_permissions_permission
                                      FOREIGN KEY (permission_id)
                                          REFERENCES permissions (id),

                                  CONSTRAINT ck_role_permissions_expiry
                                      CHECK (
                                          expires_at IS NULL
                                              OR expires_at > assigned_at
                                          ),

                                  CONSTRAINT ck_role_permissions_revocation_pair
                                      CHECK (
                                          (revoked_at IS NULL AND revoked_by IS NULL)
                                              OR
                                          (revoked_at IS NOT NULL AND revoked_by IS NOT NULL)
                                          ),

                                  CONSTRAINT ck_role_permissions_revocation_time
                                      CHECK (
                                          revoked_at IS NULL
                                              OR revoked_at >= assigned_at
                                          )
);

CREATE INDEX idx_role_permissions_role_permission
    ON role_permissions (role_id, permission_id);

CREATE INDEX idx_role_permissions_permission
    ON role_permissions (permission_id);

