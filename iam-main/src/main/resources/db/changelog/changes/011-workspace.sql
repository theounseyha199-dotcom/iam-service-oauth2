CREATE TABLE iam_activity (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 subject VARCHAR(100) NOT NULL,
 event VARCHAR(200) NOT NULL,
 success BOOLEAN NOT NULL,
 ip VARCHAR(100),
 device VARCHAR(512),
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX iam_activity_subject_time ON iam_activity(subject, occurred_at DESC);
CREATE TABLE iam_session_metadata (
 session_key VARCHAR(64) PRIMARY KEY,
 ip VARCHAR(100), device VARCHAR(512),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE iam_deactivation_request (
 subject UUID PRIMARY KEY, reason VARCHAR(500) NOT NULL,
 requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE iam_workspace_policy (
 id INTEGER PRIMARY KEY CHECK (id = 1),
 session_minutes INTEGER NOT NULL DEFAULT 30 CHECK (session_minutes BETWEEN 5 AND 1440),
 access_minutes INTEGER NOT NULL DEFAULT 5 CHECK (access_minutes BETWEEN 1 AND 60),
 refresh_minutes INTEGER NOT NULL DEFAULT 1440 CHECK (refresh_minutes BETWEEN 5 AND 43200),
 password_minimum INTEGER NOT NULL DEFAULT 8 CHECK (password_minimum BETWEEN 8 AND 64),
 require_number BOOLEAN NOT NULL DEFAULT FALSE,
 require_uppercase BOOLEAN NOT NULL DEFAULT FALSE,
 require_consent BOOLEAN NOT NULL DEFAULT TRUE,
 version BIGINT NOT NULL DEFAULT 0
);
