CREATE TABLE user_roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    role_id BIGINT NOT NULL REFERENCES roles(id),
    
    assigned_at TIMESTAMPTZ NOT NULL,
    assigned_by VARCHAR(100) NOT NULL,
    expires_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    revoked_by VARCHAR(100),
    reason VARCHAR(255),
    revocation_reason VARCHAR(255),
    version BIGINT NOT NULL DEFAULT 0,
    CHECK (expires_at IS NULL OR expires_at > assigned_at),
    CHECK ((revoked_at IS NULL) = (revoked_by IS NULL)),
    CHECK (revoked_at IS NULL OR revoked_at >= assigned_at)
);
CREATE INDEX idx_user_roles_user_target ON user_roles(user_id, role_id);
CREATE INDEX idx_user_roles_target ON user_roles(role_id);

CREATE TABLE user_permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    permission_id BIGINT NOT NULL REFERENCES permissions(id),
    effect VARCHAR(5) NOT NULL CHECK (effect IN ('GRANT', 'DENY')),
    assigned_at TIMESTAMPTZ NOT NULL,
    assigned_by VARCHAR(100) NOT NULL,
    expires_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    revoked_by VARCHAR(100),
    reason VARCHAR(255),
    revocation_reason VARCHAR(255),
    version BIGINT NOT NULL DEFAULT 0,
    CHECK (expires_at IS NULL OR expires_at > assigned_at),
    CHECK ((revoked_at IS NULL) = (revoked_by IS NULL)),
    CHECK (revoked_at IS NULL OR revoked_at >= assigned_at)
);
CREATE INDEX idx_user_permissions_user_target ON user_permissions(user_id, permission_id);
CREATE INDEX idx_user_permissions_target ON user_permissions(permission_id);

