import { chromium, expect } from '../iam-web/iam-web-reactjs/node_modules/@playwright/test/index.mjs'
import { mkdir } from 'node:fs/promises'
const base = process.env.IAM_BROWSER_URL
const username = process.env.IAM_BROWSER_USERNAME
const password = process.env.IAM_BROWSER_PASSWORD
if (!base || !username || !password) throw new Error('Browser test fixture environment is required')
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage()
const errors = []
page.on('pageerror', e => errors.push(e.message))
await mkdir('verification/browser', { recursive: true })
try {
  await page.goto(`${base}/login?lang=en`)
  await expect(page.getByRole('heading', {name: 'Sign in', exact: true})).toBeVisible()
  await expect(page.locator('.dashboard-root')).toHaveCount(0)
  await expect(page.locator('#username')).toHaveAttribute('data-slot', 'input')
  await expect(page.locator('#username')).toHaveAttribute('data-density', 'account')
  await expect(page.getByRole('button', {name: 'Sign in', exact: true})).toHaveAttribute('data-slot', 'button')
  await expect(page.locator('section.login-card')).toHaveAttribute('data-slot', 'card')
  await page.getByRole('button', {name: 'Sign in', exact: true}).click()
  await expect(page.locator('#username')).toBeFocused()
  await expect(page.locator('#username-error')).toHaveText('Complete this field.')
  await page.locator('#username').fill(username)
  await page.locator('#password').fill('wrong-password')
  await page.getByRole('button', {name: 'Show password', exact: true}).click()
  await expect(page.locator('#password')).toHaveAttribute('type', 'text')
  await page.getByRole('button', {name: 'Hide password', exact: true}).click()
  await page.getByRole('button', {name: 'Sign in', exact: true}).click()
  await expect(page.getByRole('alert')).toContainText('Unable to sign in')
  await expect(page.locator('#password')).toHaveValue('')
  await page.getByRole('link', {name: 'ខ្មែរ', exact: true}).click()
  await expect(page.locator('html')).toHaveAttribute('lang', 'km')
  await page.setViewportSize({width: 390, height: 844})
  await page.screenshot({path: 'verification/browser/react-login-km-mobile.png', fullPage: true})
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Mobile overflow')
  await page.locator('a[lang="en"]').click()
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  await page.locator('#username').fill(username)
  await page.locator('#password').fill(password)
  await page.getByRole('button', {name: 'Sign in', exact: true}).click()
  await expect(page).toHaveURL(`${base}/`)
  await page.goto(`${base}/?lang=en`)
  await expect(page.getByRole('heading', {name: 'Overview', exact: true})).toBeVisible()
  await page.setViewportSize({width: 1280, height: 900})
  await page.goto(`${base}/profile/edit`)
  await page.locator('#givenName').fill('React browser check')
  await page.getByRole('link', {name: 'Connected apps', exact: true}).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', {name: 'Keep editing', exact: true}).click()
  await expect(page.locator('#givenName')).toHaveValue('React browser check')
  await page.getByRole('button', {name: 'Save changes', exact: true}).click()
  await expect(page.getByRole('status')).toHaveText('Your changes have been saved.')
  await expect(page.locator('#givenName')).toHaveValue('React browser check')
  await page.locator('#gender').selectOption('other')
  await page.locator('#birthdate').fill('2000-01-02')
  await page.getByRole('link', {name: 'Connected apps', exact: true}).click()
  await page.getByRole('button', {name: 'Leave page', exact: true}).click()
  await expect(page.getByText('No connected applications.', {exact: true})).toBeVisible()
  await page.goto(`${base}/oauth2/consent?client_id=iam-web-client&scope=openid%20profile%20email&state=react-browser-state`)
  await expect(page.getByRole('heading', {name: 'Authorize application', exact: true})).toBeVisible()
  await expect(page.locator('input[name=state]').first()).toHaveValue('react-browser-state')
  await expect(page.locator('input[name=scope][value=profile]')).toBeChecked()
  await page.locator('a[lang="km"]').click()
  await expect(page.locator('html')).toHaveAttribute('lang', 'km')
  await expect(page.locator('input[name=state]').first()).toHaveValue('react-browser-state')
  await page.locator('a[lang="en"]').click()
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  await page.goto(`${base}/profile/accounts`)
  await expect(page.getByText('No provider accounts are connected yet.', {exact: true})).toBeVisible()
  for (const provider of ['google', 'github', 'facebook', 'telegram']) {
    // Stop at the provider boundary; real credentials/consent must never be used by this check.
    const providerForm = page.locator(`form[action$="/profile/accounts/link/${provider}"]`)
    let authorization
    let startStatus
    const intercept = async route => {
      const response = await route.fetch({maxRedirects: 0})
      startStatus = response.status()
      authorization = new URL(response.headers().location, base)
      await route.fulfill({contentType: 'text/html', body: '<p>Provider authorization boundary</p>'})
    }
    const pattern = `**/profile/accounts/link/${provider}`
    await page.route(pattern, intercept)
    await providerForm.getByRole('button').click()
    await expect.poll(() => authorization?.searchParams.get('state')).toBeTruthy()
    expect(startStatus).toBe(302)
    expect(authorization.origin).not.toBe(new URL(base).origin)
    await page.unroute(pattern, intercept)
    await page.goto(`${base}/login/oauth2/code/${provider}?error=access_denied&state=${encodeURIComponent(authorization.searchParams.get('state'))}`)
    await expect(page).toHaveURL(`${base}/profile/accounts?error`)
    await expect(page.getByRole('heading', {name: 'Linked accounts', exact: true})).toBeVisible()
    await expect(page.getByRole('alert')).toContainText('The provider connection was cancelled.')
  }
  await page.goto(`${base}/profile/password`)
  await expect(page.locator('#currentPassword')).toBeVisible()
  await page.screenshot({path: 'verification/browser/react-account.png', fullPage: true})
  await page.getByRole('button', {name: 'Sign out', exact: true}).click()
  await expect(page).toHaveURL(/\/login\?logout/)
  await page.goto(`${base}/forgot-password`)
  await expect(page.locator('#email')).toBeVisible()
  await page.goto(`${base}/reset-password`)
  await expect(page.getByRole('alert')).toContainText('invalid, expired')
  await page.goto(`${base}/verify-email`)
  await expect(page.locator('#code')).toBeVisible()
  await expect(page.locator('#code')).toHaveAttribute('autocomplete', 'one-time-code')
  await page.goto(`${base}/register`)
  let invalidRegistrationPosts = 0
  const registrationRequest = request => { if (request.method() === 'POST' && new URL(request.url()).pathname === '/register') invalidRegistrationPosts++ }
  page.on('request', registrationRequest)
  await page.locator('#username').fill('a')
  await page.locator('#email').fill('react@example.com')
  await page.locator('#givenName').fill('React')
  await page.locator('#familyName').fill('Test')
  await page.locator('#password').fill('short')
  await page.locator('#confirmPassword').fill('different')
  await page.getByRole('button', {name: 'Create account', exact: true}).click()
  await expect(page.locator('#username')).toHaveAttribute('aria-invalid', 'true')
  await expect(page.locator('#username')).toBeFocused()
  await expect(page.locator('#givenName')).toHaveValue('React')
  await expect(page.locator('#password')).toHaveValue('')
  await expect(page.locator('#confirmPassword-error')).toHaveText('The passwords must match.')
  if (invalidRegistrationPosts !== 0) throw new Error('Invalid registration was posted before Zod validation')
  page.off('request', registrationRequest)
  await page.screenshot({path: 'verification/browser/react-validation.png', fullPage: true})
  await page.goto(`${base}/verify-email`)
  await page.locator('#email').fill(process.env.IAM_BROWSER_OTP_EMAIL)
  await page.locator('#code').fill('000000')
  await page.getByRole('button', {name: 'Verify email', exact: true}).click()
  await expect(page.getByRole('alert')).toContainText('incorrect, expired')
  await expect(page.locator('#code')).toHaveValue('')
  await expect(page.locator('#email')).toHaveValue(process.env.IAM_BROWSER_OTP_EMAIL)
  await page.screenshot({path: 'verification/browser/react-otp-validation.png', fullPage: true})
  await page.locator('#code').fill(process.env.IAM_BROWSER_OTP_CODE)
  await page.getByRole('button', {name: 'Show verification code', exact: true}).click()
  await expect(page.locator('#code')).toHaveAttribute('type', 'text')
  await page.getByRole('button', {name: 'Hide verification code', exact: true}).click()
  await page.getByRole('button', {name: 'Verify email', exact: true}).click()
  await expect(page.getByRole('status')).toContainText('Your email is verified')
  await page.goto(`${base}/login`)
  await page.locator('#username').fill(process.env.IAM_BROWSER_OTP_EMAIL)
  await page.locator('#password').fill(password)
  await page.getByRole('button', {name: 'Sign in', exact: true}).click()
  await expect(page).toHaveURL(`${base}/`)
  await page.getByRole('button', {name: 'Sign out', exact: true}).click()
  await page.goto(`${base}/login?lang=en`)
  await page.locator('#username').fill(process.env.IAM_BROWSER_LINKED_USERNAME)
  await page.locator('#password').fill(password)
  await page.getByRole('button', {name: 'Sign in', exact: true}).click()
  await expect(page).toHaveURL(`${base}/`)
  await page.goto(`${base}/profile/accounts`)
  for (const label of ['Google', 'GitHub', 'Facebook', 'Telegram']) {
    const row = page.locator('.record-list > li').filter({has: page.getByRole('heading', {name: label, exact: true})})
    await expect(row.getByText('Connected', {exact: true})).toBeVisible()
    await expect(row.getByRole('link', {name: 'Disconnect', exact: true})).toBeVisible()
    await expect(page.getByRole('button', {name: `Connect ${label}`, exact: true})).toHaveCount(0)
  }
  await page.reload()
  await expect(page.locator('.record-list > li')).toHaveCount(4)
  await page.screenshot({path: 'verification/browser/linked-providers.png', fullPage: true})
  if (errors.length) throw new Error(errors.join('\n'))
  console.log('React browser checks passed: login success/failure, CSRF forms, Khmer/mobile, profile save, unsaved navigation, empty lists, logout, recovery and registration validation.')
} finally { await browser.close() }
